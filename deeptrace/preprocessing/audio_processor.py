"""Audio preprocessing, acoustic feature extraction, and spectrogram computation."""

from __future__ import annotations

from pathlib import Path
from typing import Any, Dict, Optional, Tuple

import numpy as np
import soundfile as sf

from deeptrace.config import Settings, get_settings
from deeptrace.logging_utils import get_logger

logger = get_logger(__name__)


class AudioPreprocessor:
    """Preprocesses audio signals and extracts acoustic/spectral features."""

    def __init__(self, settings: Optional[Settings] = None):
        self.settings = settings or get_settings()

    def load_audio(
        self, path: Path | str, target_sr: Optional[int] = None
    ) -> Tuple[np.ndarray, int]:
        """Load audio into mono floating-point numpy array at target sample rate."""
        target_sr = target_sr or self.settings.audio_sample_rate
        data, sr = sf.read(str(path), dtype="float32")

        # Convert to mono if multi-channel
        if data.ndim > 1:
            data = np.mean(data, axis=1)

        # Simple linear resampling if sample rate differs
        if sr != target_sr and len(data) > 0:
            duration = len(data) / sr
            new_length = int(round(duration * target_sr))
            indices = np.linspace(0, len(data) - 1, new_length)
            data = np.interp(indices, np.arange(len(data)), data).astype(np.float32)
            sr = target_sr

        # Cap length to processing_max_seconds
        max_samples = int(self.settings.processing_max_seconds * sr)
        if len(data) > max_samples:
            data = data[:max_samples]

        return data, sr

    def compute_spectrogram(
        self, audio: np.ndarray, sr: int, n_fft: int = 1024, hop_length: int = 512
    ) -> np.ndarray:
        """Compute short-time Fourier transform (STFT) log-magnitude spectrogram."""
        if len(audio) < n_fft:
            audio = np.pad(audio, (0, n_fft - len(audio)), mode="constant")

        # Hann window
        window = np.hanning(n_fft)
        num_frames = 1 + (len(audio) - n_fft) // hop_length
        spectrogram = np.empty((n_fft // 2 + 1, num_frames), dtype=np.float32)

        for i in range(num_frames):
            start = i * hop_length
            segment = audio[start : start + n_fft] * window
            fft_res = np.fft.rfft(segment)
            spectrogram[:, i] = np.abs(fft_res)

        log_spec = 20 * np.log10(spectrogram + 1e-6)
        return log_spec

    def extract_acoustic_features(
        self, audio: np.ndarray, sr: int
    ) -> Dict[str, Any]:
        """Extract measurable acoustic features indicative of synthetic speech / voice clones.

        Synthetic speech generated by neural TTS models often has:
        - Abrupt cutoffs in high-frequency spectral rolloff
        - Unnatural spectral flatness across unvoiced segments
        - Zero-crossing rate irregularities
        - Overly uniform energy envelope (lack of natural breath/pause dynamics)
        """
        if len(audio) == 0:
            return {"error": "empty_audio"}

        # 1. Energy & RMS
        frame_len = 512
        num_frames = len(audio) // frame_len
        if num_frames == 0:
            rms_vals = np.array([float(np.sqrt(np.mean(audio**2)))])
        else:
            frames = audio[: num_frames * frame_len].reshape(num_frames, frame_len)
            rms_vals = np.sqrt(np.mean(frames**2, axis=1) + 1e-9)

        mean_energy = float(np.mean(rms_vals))
        energy_std = float(np.std(rms_vals))
        # Silence ratio (frames with < 5% of peak energy)
        silence_thresh = 0.05 * (np.max(rms_vals) + 1e-6)
        silence_ratio = float(np.mean(rms_vals < silence_thresh))

        # 2. Zero-crossing rate (ZCR)
        signs = np.sign(audio)
        zcr = float(np.mean(np.abs(np.diff(signs)) > 0))

        # 3. Spectral analysis using STFT
        spec = self.compute_spectrogram(audio, sr)
        freq_bins = spec.shape[0]
        freqs = np.linspace(0, sr / 2, freq_bins)

        # Spectral Centroid (mean frequency weighted by magnitude)
        linear_mag = 10 ** (spec / 20.0)
        col_sums = np.sum(linear_mag, axis=0) + 1e-6
        centroids = np.sum(freqs[:, None] * linear_mag, axis=0) / col_sums
        mean_centroid = float(np.mean(centroids))

        # Spectral Flatness (geometric mean / arithmetic mean)
        # Highly flat spectrum is noise-like or artifact of imperfect vocoder
        geom_mean = np.exp(np.mean(np.log(linear_mag + 1e-9), axis=0))
        arith_mean = np.mean(linear_mag, axis=0) + 1e-9
        flatness = float(np.mean(geom_mean / arith_mean))

        # High-frequency energy cutoff check (vocoder cutoff above 7.5 kHz or Nyquist)
        hf_band = freqs > (sr * 0.45)
        hf_energy_ratio = float(np.mean(linear_mag[hf_band, :]) / (np.mean(linear_mag) + 1e-6))

        return {
            "duration_s": round(len(audio) / sr, 3),
            "sample_rate": sr,
            "mean_energy_rms": round(mean_energy, 4),
            "energy_dynamic_std": round(energy_std, 4),
            "silence_ratio": round(silence_ratio, 3),
            "zero_crossing_rate": round(zcr, 4),
            "spectral_centroid_hz": round(mean_centroid, 1),
            "spectral_flatness": round(flatness, 5),
            "hf_cutoff_energy_ratio": round(hf_energy_ratio, 4),
        }
